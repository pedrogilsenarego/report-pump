/**
 * Generates translations/specFields.ts from app/assets/Table_Field_Names.xlsx.
 *
 *   node scripts/generate-spec-fields.cjs
 *
 * The workbook holds every UI label of the spec keyed by ScreenField number — the `SF#nnn`
 * every drawing and #Actions.xlsx refers to — with columns
 *   A # | B SOURCE | C DEFAULT CONDITION | D PT | E EN | F FR | G ES
 * FR and ES are empty in the bundle; they are carried through so a later revision of the
 * workbook fills them without touching this script. See docs/spec-inputs.md.
 *
 * Re-run whenever the client sends a new revision of the workbook. The output is generated —
 * do not edit it by hand.
 */

const fs = require("fs");
const path = require("path");
const XLSX = require("xlsx");

const root = path.join(__dirname, "..");
const source = path.join(root, "app", "assets", "Table_Field_Names.xlsx");
const target = path.join(root, "translations", "specFields.ts");

const workbook = XLSX.readFile(source);
const sheet = workbook.Sheets[workbook.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: "" });

const clean = (value) => String(value ?? "").replace(/\s+/g, " ").trim();

const fields = {};
const duplicates = [];
let reserved = 0;
for (const row of rows) {
  const number = Number(String(row[0]).trim());
  // Title rows and the header row have no numeric `#`.
  if (!Number.isInteger(number) || number <= 0) continue;

  const entry = {
    source: clean(row[1]),
    pt: clean(row[3]),
    en: clean(row[4]),
    fr: clean(row[5]),
    es: clean(row[6]),
  };
  // The workbook reserves numbers with no text in any language — nothing to translate.
  if (!entry.pt && !entry.en && !entry.fr && !entry.es) {
    reserved += 1;
    continue;
  }
  if (fields[number]) duplicates.push(number);
  fields[number] = entry;
}

const numbers = Object.keys(fields).map(Number).sort((a, b) => a - b);
const lines = numbers.map((n) => {
  const f = fields[n];
  const parts = [`source: ${JSON.stringify(f.source)}`, `pt: ${JSON.stringify(f.pt)}`, `en: ${JSON.stringify(f.en)}`];
  if (f.fr) parts.push(`fr: ${JSON.stringify(f.fr)}`);
  if (f.es) parts.push(`es: ${JSON.stringify(f.es)}`);
  return `  ${n}: { ${parts.join(", ")} },`;
});

const output = `// GENERATED by scripts/generate-spec-fields.cjs from app/assets/Table_Field_Names.xlsx.
// Do not edit by hand — re-run the script when the workbook changes.
/* eslint-disable */

export type SpecField = {
  /** The screen or pop-up the label belongs to, e.g. "Screen#01". */
  source: string;
  pt: string;
  en: string;
  fr?: string;
  es?: string;
};

/** ScreenField number (SF#nnn) -> label per language. ${numbers.length} entries. */
export const SPEC_FIELDS: Record<number, SpecField> = {
${lines.join("\n")}
};
`;

fs.writeFileSync(target, output);
console.log(
  `Wrote ${numbers.length} fields to ${path.relative(root, target)}, skipped ${reserved} with no text` +
    (duplicates.length ? ` (duplicate numbers, last wins: ${duplicates.join(", ")})` : "")
);
