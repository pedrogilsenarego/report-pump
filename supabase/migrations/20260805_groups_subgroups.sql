-- in translations/languages/{en,pt}.ts, so the check-list display does not regress.
-- Real content arrives with Report_Actions.xlsx via Action#22.
-- ---------------------------------------------------------------------------
insert into public.groups (code, name) values
  (1, '{"en": "Pre-Test Inspections", "pt": "Inspeções Pré Ensaio"}'::jsonb),
  (2, '{"en": "Checks and Tests (VE)", "pt": "Verificações e Ensaios (VE)"}'::jsonb)
on conflict (code) do nothing;
